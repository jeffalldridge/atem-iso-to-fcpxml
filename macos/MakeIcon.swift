// App icon uses the same shapes and palette as docs/site/favicon.svg.
import AppKit
let image = NSImage(size: NSSize(width: 1024, height: 1024))
image.lockFocus()
let transform = NSAffineTransform()
transform.scale(by: 16)
transform.concat()
NSColor(calibratedRed: 13/255, green: 13/255, blue: 18/255, alpha: 1).setFill()
NSBezierPath(roundedRect: NSRect(x: 0, y: 0, width: 64, height: 64), xRadius: 14, yRadius: 14).fill()
NSColor(calibratedRed: 146/255, green: 146/255, blue: 164/255, alpha: 1).setFill()
NSBezierPath(roundedRect: NSRect(x: 8, y: 18, width: 22, height: 28), xRadius: 4, yRadius: 4).fill()
let orange = NSColor(calibratedRed: 1, green: 138/255, blue: 76/255, alpha: 1)
orange.setStroke(); orange.setFill()
let line = NSBezierPath(); line.move(to: NSPoint(x: 34, y: 32)); line.line(to: NSPoint(x: 46, y: 32))
line.lineWidth = 5; line.lineCapStyle = .round; line.stroke()
let arrow = NSBezierPath(); arrow.move(to: NSPoint(x: 43, y: 24)); arrow.line(to: NSPoint(x: 53, y: 32))
arrow.line(to: NSPoint(x: 43, y: 40)); arrow.close(); arrow.fill()
image.unlockFocus()
let bitmap = NSBitmapImageRep(data: image.tiffRepresentation!)!
try bitmap.representation(using: .png, properties: [:])!.write(to: URL(fileURLWithPath: CommandLine.arguments[1]))
